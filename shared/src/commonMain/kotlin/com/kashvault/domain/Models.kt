@Serializable
data class InboxReminderSettings(
    val enabled: Boolean = true,
    val hour: Int = 21,
    val minute: Int = 0,
)

@Serializable
data class UserProfile(
    val id: String,
    val name: String,
    val email: String,
    val mobile: String,
    val geminiApiKey: String? = null,
