package com.kashvault.domain

import kotlinx.serialization.Serializable

@Serializable
data class Category(
    val id: String,
    val name: String,
    val icon: String,
    val color: String,
    val type: String? = null,
    val keywords: List<String>? = null,
)

@Serializable
data class Expense(
    val id: String,
    val amount: Double,
    val categoryId: String,
    val timestamp: String,
    val note: String? = null,
    val type: String? = null,
    val isAutoGenerated: Boolean? = null,
    val sourceId: String? = null,
    val destinationId: String? = null,
    val dueKind: String? = null,
    val dueEntityId: String? = null,
)

fun Expense.isTransfer(): Boolean = type == Constants.TYPE_TRANSFER
fun Expense.isIncome(): Boolean = type == "income"
fun Expense.isSpend(): Boolean = !isIncome() && !isTransfer()

@Serializable
data class Person(
    val id: String,
    val name: String,
    val phone: String? = null,
)

@Serializable
data class BorrowLend(
    val id: String,
    val person: String,
    val amount: Double,
    val type: String,
    val settled: Boolean,
    val timestamp: String,
    val note: String? = null,
    val personId: String? = null,
)

@Serializable
data class RecurringBill(
    val id: String,
    val name: String,
    val amount: Double,
    val categoryId: String,
    val frequency: String,
    val dueDate: String,
    val lastProcessedMonth: String? = null,
    val sourceId: String? = null,
    val type: String = "expense",
)

fun RecurringBill.isIncome(): Boolean = type == "income"

@Serializable
data class Budget(
    val categoryId: String,
    val limit: Double,
)

typealias RecurringFrequency = String // Monthly, Quarterly, Yearly, OneTime

@Serializable
data class Investment(
    val id: String,
    val name: String,
    val amount: Double,
    val investedAmount: Double? = null,
    val type: String,
    val frequency: String? = null,
    val timestamp: String,
    val dueDate: String? = null,
    val lastProcessedMonth: String? = null,
    val sourceId: String? = null,
)

@Serializable
data class Insurance(
    val id: String,
    val name: String,
    val premium: Double,
    val frequency: String,
    val dueDate: String,
    val lastProcessedMonth: String? = null,
    val sourceId: String? = null,
)

@Serializable
data class Loan(
    val id: String,
    val name: String,
    val totalAmount: Double,
    val annualInterestRate: Double? = null,
    val tenureMonths: Int? = null,
    val emi: Double,
    val remainingAmount: Double,
    val remainingInterest: Double? = null,
    val outstandingTotal: Double? = null,
    val totalPrepaid: Double? = null,
    val emisPaid: Int? = null,
    val dueDate: String,
    val startDate: String? = null,
    val lastProcessedMonth: String? = null,
    val principalPerEmi: Double? = null,
    val interestPerEmi: Double? = null,
    val sourceId: String? = null,
)

@Serializable
data class SavingsGoal(
    val id: String,
    val name: String,
    val target: Double,
    val current: Double,
    val completed: Boolean? = null,
)

@Serializable
data class EmergencyFund(
    val targetMonths: Int,
    val monthlyRequirement: Double,
    val currentSaved: Double,
)

@Serializable
data class Secret(
    val id: String,
    val title: String,
    val tag: String? = null,
    val content: String,
    val color: String? = null,
    val timestamp: String,
)

@Serializable
data class SyncSettings(
    val autoSync: Boolean,
    val lastBackupAt: String? = null,
    val lastRestoreAt: String? = null,
    val lastSyncAt: String? = null,
    val lastLocalChangeAt: String? = null,
    val cloudBackupAt: String? = null,
)

@Serializable
data class PaymentSource(
    val id: String,
    val name: String,
    val kind: String,
    val last4: String? = null,
    val icon: String = "🏦",
    val color: String = "#339AF0",
    val keywords: List<String>? = null,
    val openingBalance: Double = 0.0,
    val statementDueDate: String? = null,
    val lastProcessedMonth: String? = null,
    val payFromSourceId: String? = null,
