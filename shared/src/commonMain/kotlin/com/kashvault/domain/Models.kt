@Serializable
data class GoogleSession(
    val userId: String,
    val email: String? = null,
    val displayName: String? = null,
    val imageUrl: String? = null,
    val accessToken: String? = null,
    val refreshToken: String? = null,
    val idToken: String? = null,
    val expiresAtEpochMs: Long? = null,
)

@Serializable
data class FinanceSnapshot(
    val categories: List<Category> = emptyList(),
    val paymentSources: List<PaymentSource> = emptyList(),
    val expenses: List<Expense> = emptyList(),
    val borrowLend: List<BorrowLend> = emptyList(),
    val budgets: List<Budget> = emptyList(),
    val investments: List<Investment> = emptyList(),
    val insurances: List<Insurance> = emptyList(),
    val loans: List<Loan> = emptyList(),
    val savingsGoals: List<SavingsGoal> = emptyList(),
    val secrets: List<Secret> = emptyList(),
    val emergencyFund: EmergencyFund = EmergencyFund(6, 0.0, 0.0),
    val userProfile: UserProfile? = null,
    val syncSettings: SyncSettings = SyncSettings(autoSync = false),
    val isLocalMode: Boolean = false,
    val googleSession: GoogleSession? = null,
    val authChoice: String? = null,
    val googleWebClientId: String = "",
    val lastPaymentSourceId: String? = null,
    val inboxItems: List<InboxItem> = emptyList(),
    val people: List<Person> = emptyList(),
    val recurringBills: List<RecurringBill> = emptyList(),
    val setupCompleted: Boolean = false,
    val smsScanKeywords: List<String> = emptyList(),
    val inboxReminder: InboxReminderSettings = InboxReminderSettings(),
    val periodicSmsScanEnabled: Boolean = false,
    val accountKey: String = Constants.ACCOUNT_KEY_LOCAL,
    val geminiModel: String = "",
    val vaultLockEnabled: Boolean = false,
)

typealias Timeframe = String // daily, weekly, monthly, yearly

