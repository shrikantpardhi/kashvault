package com.kashvault.db

import com.kashvault.domain.*
import kotlinx.serialization.json.Json

private val json = Json { ignoreUnknownKeys = true }

private inline fun <reified T> decodeJsonOrNull(raw: String?): T? =
    raw?.let { runCatching { json.decodeFromString<T>(it) }.getOrNull() }

fun Categories.toDomain(): Category = Category(
    id = id,
    name = name,
    icon = icon,
    color = color,
    type = type,
    keywords = decodeJsonOrNull<List<String>>(keywords_json),
)

