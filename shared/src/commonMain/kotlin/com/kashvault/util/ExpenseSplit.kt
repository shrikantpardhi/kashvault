package com.kashvault.util

import com.kashvault.domain.Expense
import com.kashvault.domain.isTransfer
import kotlin.math.abs

data class SplitExpenseParts(
    val first: Expense,
    val second: Expense,
)

fun planExpenseSplit(
    original: Expense,
    firstCategoryId: String,
    firstAmount: Double,
    secondCategoryId: String,
    secondId: String,
    firstId: String,
): SplitExpenseParts? {
    if (original.isTransfer()) return null
    if (firstCategoryId.isBlank() || secondCategoryId.isBlank()) return null
    if (firstId.isBlank() || secondId.isBlank() || firstId == secondId || firstId == original.id || secondId == original.id) {
        return null
    }
    val first = roundCurrency(firstAmount)
    val second = roundCurrency(original.amount - first)
    if (first <= 0.0 || second <= 0.0) return null
    if (abs(first + second - original.amount) > 0.02) return null
    fun part(id: String, categoryId: String, amount: Double) = original.copy(
        id = id,
        amount = amount,
        categoryId = categoryId,
        isAutoGenerated = false,
    )
    return SplitExpenseParts(
        first = part(firstId, firstCategoryId, first),
        second = part(secondId, secondCategoryId, second),
    )
}
